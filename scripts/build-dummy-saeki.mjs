async function upsert(ds, peopleProp, titleProp, name, props){
  const full=MARK+name;
  let existing;
  try{
    const r=await notion.dataSources.query({data_source_id:ds,page_size:100,filter:{property:peopleProp,people:{contains:SAEKI}}});
    existing=r.results.find(p=>((p.properties?.[titleProp]?.title||[]).map(x=>x.plain_text).join(""))===full);
  }catch(e){ console.log("  (検索warn:",String(e).slice(0,80),")"); }
  if(existing){ console.log("既存:",full,"→",existing.id); return existing.id; }
  const created=await notion.pages.create({parent:{data_source_id:ds},properties:{[titleProp]:{title:[{text:{content:full}}]},...props}});
  console.log("作成:",full,"→",created.id);
  return created.id;
}

